"""Regenerate constraints.txt: the full pinned runtime dependency tree (B-08, R-05).

    python scripts/lock.py        (make lock)

requirements.txt pins the direct dependencies (the <= 4 the app imports). This resolves
them in a throwaway venv, only from releases at least COOLDOWN old, and writes every
installed package, transitive ones included, to constraints.txt. make setup installs
with -c constraints.txt, so a fresh clone gets exactly these versions.
"""

import subprocess
import sys
import tempfile
import venv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COOLDOWN = "P14D"  # a hijacked release usually gets yanked within days


def main() -> int:
    with tempfile.TemporaryDirectory(dir=ROOT / ".cache") as tmp:
        venv.create(tmp, with_pip=False)
        py = Path(tmp) / ("Scripts/python.exe" if sys.platform == "win32" else "bin/python")
        pip = [sys.executable, "-m", "pip", "--python", str(py)]  # this venv's pip (needs >= 26.1)
        subprocess.run([*pip, "install", "--quiet", "--uploaded-prior-to", COOLDOWN,
                        "-r", ROOT / "requirements.txt"], check=True)
        frozen = subprocess.run([*pip, "freeze", "--all"], capture_output=True, text=True,
                                check=True).stdout
    lines = sorted(ln for ln in frozen.splitlines() if "==" in ln)
    header = ["# Generated by scripts/lock.py (make lock). Do not edit by hand.",
              f"# Full runtime tree for requirements.txt, releases at least {COOLDOWN[1:-1]} days old."]
    (ROOT / "constraints.txt").write_text("\n".join(header + lines) + "\n", encoding="utf-8", newline="\n")
    print(f"constraints.txt: {len(lines)} pinned packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
